"""Read-only access to the Content Library index (library/catalog.json).

The catalog is generated by `python library/tools/build_catalog.py` and lists every template,
effect, transition, text treatment, carousel style, skill, prompt, production recipe
(`library/recipes/<id>/recipe.json`, schema recipe/v1) and model playbook (`library/models/<model>/PLAYBOOK.md`).
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "library" / "catalog.json"
FIELDS = (("name", 4.0), ("tags", 3.0), ("id", 2.0), ("type", 2.0), ("description", 1.5), ("kit", 1.0), ("use", 0.5))
PUBLIC_KEYS = ("id", "name", "type", "medium", "formats", "engine", "description", "tags", "kit", "use",
               "cost", "requires", "status", "preview", "path", "notes", "company", "source_url", "technique_detail")


@lru_cache(maxsize=1)
def _load(mtime: float) -> list[dict]:
    return json.loads(CATALOG.read_text(encoding="utf-8"))["items"]


def items(company=None) -> list[dict]:
    base = _load(CATALOG.stat().st_mtime) if CATALOG.exists() else []
    if company is None:
        return base
    # The database holds curated company additions, not another library/catalog.json.
    from engine.techniques.models import StoredTechnique
    return [*base, *(item.data for item in StoredTechnique.objects.filter(company=company))]


def _tokens(text: str) -> list[str]:
    return [t for t in re.split(r"[^\wåäöÅÄÖ:+-]+", text.lower()) if len(t) > 1]


def _score(item: dict, words: list[str]) -> float:
    total = 0.0
    for word in words:
        for key, weight in FIELDS:
            value = item.get(key, "")
            text = (" ".join(value) if isinstance(value, list) else str(value)).lower()
            if word in _tokens(text):
                total += weight
            elif word in text:
                total += weight * 0.5
    if not words:
        total = 1.0
    if total == 0:
        return 0.0
    if item.get("status") == "verified":
        total *= 1.6
    elif item.get("status") == "broken":
        total *= 0.2
    if item.get("preview"):
        total *= 1.2
    return total


def _public(item: dict) -> dict:
    return {key: item.get(key) for key in PUBLIC_KEYS}


def search(query: str = "", *, type: str = "", format: str = "", medium: str = "", kit: str = "",
           verified_only: bool = False, limit: int = 15, feedback: dict | None = None,
           company=None) -> dict:
    """`feedback` (engine.review.lessons.library_feedback) ranks items by what the owner liked/disliked before."""
    limit = max(1, min(int(limit), 50))
    words = _tokens(query)
    all_items = items(company)
    pool = [
        i for i in all_items
        if (not type or i["type"] == type)
        and (not medium or i["medium"] == medium)
        and (not kit or i["kit"] == kit)
        and (not format or format in i["formats"] or "any" in i["formats"])
        and (not verified_only or i["status"] == "verified")
    ]
    feedback = feedback or {}
    ranked = sorted(((_score(i, words) * feedback.get(i["id"], {}).get("multiplier", 1.0), i) for i in pool),
                    key=lambda pair: -pair[0])
    hits = []
    for score, item in ranked:
        if score <= 0 or len(hits) >= limit:
            continue
        hit = _public(item)
        if item["id"] in feedback:
            hit["our_feedback"] = {k: v for k, v in feedback[item["id"]].items() if k != "multiplier"}
        hits.append(hit)
    return {"total_in_library": len(all_items), "matches": len(hits), "results": hits}


def get(item_id: str, *, company=None) -> dict:
    """One scoped item; recipes also carry full recipe/v1 data."""
    for item in items(company):
        if item["id"] == item_id:
            result = _public(item)
            recipe = (ROOT / item["path"]).with_name("recipe.json") if item["type"] == "recipe" else None
            if recipe and recipe.exists():
                result["recipe"] = json.loads(recipe.read_text(encoding="utf-8"))
            return result
    raise ValueError(f"Okänt biblioteks-id '{item_id}'. Sök med search_content_library.")
