#!/usr/bin/env python3
"""
build-captions.py — turn a tightened transcript into PERSA word captions.

    python scripts/build-captions.py assets/transcript-tight.json \
        --out seg-01-cold-open/captions.html [--emphasis FREE,NEVER,ONE]

PERSA captions are the least forgiving part of the style and the easiest to get
wrong, because the temptation is to animate them. Measured off the reference at
30fps (reference/stills/10-caption-hardcut-30fps.png):

  * ONE WORD on screen at a time. Never a phrase, never an accumulating line.
  * It HARD-CUTS. No fade, no scale-in, no pop. Zero frames of transition.
    The next word simply replaces the previous one on its onset frame.
  * Position is FIXED at 73% of frame height, horizontally centred. It does not
    track the speaker, it does not reflow, it does not move for long words.
  * A word is on screen for exactly as long as it is spoken — the shortest
    measured hold was 4 frames (133ms).
  * ALL CAPS, Inter 700, white, soft dark halo. No box, no stroke, no shadow
    offset you can point at.

--emphasis promotes the named words to the big outlined treatment that sits
BEHIND the subject matte (see reference/captions.md §3). Use it sparingly: the
reference averages roughly one per 8 seconds.

⚠ Timing MUST come from transcript-tight.json. The tighten pass moves every word
  onset; timing against the original transcript shows up as "the graphics are
  all slightly early", never as an error.
"""
import os as _os, sys as _sys; _sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
import _win_utf8  # noqa: E402,F401  content-engine import: UTF-8 text I/O on Windows
import argparse, html, json, sys, pathlib

FPS = 30

def load_words(path):
    """Accept the shapes tighten-cuts.py can emit; fail loudly on anything else."""
    d = json.loads(pathlib.Path(path).read_text())
    if isinstance(d, dict):
        for k in ("words", "segments", "result"):
            if k in d:
                d = d[k]
                break
    if not isinstance(d, list):
        sys.exit("could not find a word list in the transcript JSON")
    out = []
    for w in d:
        if not isinstance(w, dict):
            continue
        text = w.get("word") or w.get("text") or w.get("value")
        start = w.get("start", w.get("s", w.get("from")))
        end = w.get("end", w.get("e", w.get("to")))
        if text is None or start is None:
            continue
        text = str(text).strip()
        if not text:
            continue
        out.append({"t": text, "s": float(start),
                    "e": float(end) if end is not None else float(start) + .25})
    if not out:
        sys.exit("transcript parsed but no timed words found")
    return out

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("transcript")
    ap.add_argument("--out", required=True)
    ap.add_argument("--emphasis", default="", help="comma-separated words to promote")
    ap.add_argument("--strip", default=".,!?;:\"'",
                    help="punctuation removed from the on-screen word")
    a = ap.parse_args()

    emph = {w.strip().upper() for w in a.emphasis.split(",") if w.strip()}
    words = load_words(a.transcript)

    lines, n_emph = [], 0
    for w in words:
        txt = w["t"].strip(a.strip).upper()
        if not txt:
            continue
        f_in = round(w["s"] * FPS)
        f_out = max(f_in + 3, round(w["e"] * FPS))   # never shorter than 3f
        if txt in emph:
            n_emph += 1
            lines.append(
                f'  <div class="clip pa-emph" data-in="{f_in}" data-out="{f_out}">'
                f'{html.escape(txt)}</div>')
        else:
            lines.append(
                f'  <div class="clip pa-caption" data-in="{f_in}" data-out="{f_out}">'
                f'{html.escape(txt)}</div>')

    body = "\n".join(lines)
    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "<!-- PERSA captions — generated by scripts/build-captions.py.\n"
        "     Word captions live ABOVE the subject matte (z 50).\n"
        "     .pa-emph lives BELOW it (z 20) so the head occludes it.\n"
        "     Do not add a transition to .pa-caption. It hard-cuts. -->\n"
        f'<div class="pa-caption-track">\n{body}\n</div>\n')

    dur = words[-1]["e"] - words[0]["s"]
    print(f"{len(lines)} words -> {out}")
    print(f"  {n_emph} promoted to emphasis"
          f"  ({dur/max(n_emph,1):.1f}s apart; the reference averages ~8s)")
    print(f"  span {words[0]['s']:.2f}s -> {words[-1]['e']:.2f}s ({dur:.1f}s)")

if __name__ == "__main__":
    main()
